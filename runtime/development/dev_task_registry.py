"""
SAPIANTA Development Task Registry

Tracks development tasks generated by:

- sapianta discuss
- dev orchestrator
- future autonomous development agents

Purpose:
Provide deterministic tracking of the development backlog.
"""

from typing import List, Dict


class DevTaskRegistry:
    """
    Registry for development tasks.
    """

    def __init__(self):
        self.active_tasks: List[Dict] = []
        self.completed_tasks: List[Dict] = []
        self.rejected_tasks: List[Dict] = []

    def add_task(self, task: Dict) -> None:
        """
        Register a new development task.
        """
        self.active_tasks.append(task)

    def complete_task(self, task: Dict) -> None:
        """
        Mark task as completed.
        """
        if task in self.active_tasks:
            self.active_tasks.remove(task)
            self.completed_tasks.append(task)

    def reject_task(self, task: Dict) -> None:
        """
        Mark task as rejected.
        """
        if task in self.active_tasks:
            self.active_tasks.remove(task)
            self.rejected_tasks.append(task)

    def get_active_tasks(self) -> List[Dict]:
        return list(self.active_tasks)

    def get_completed_tasks(self) -> List[Dict]:
        return list(self.completed_tasks)

    def get_rejected_tasks(self) -> List[Dict]:
        return list(self.rejected_tasks)